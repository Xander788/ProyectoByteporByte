    private void animarParabrisas() {
        String ruta = "src/images/Parabrisas" + frame + ".png";
        File archivo = new File(ruta);
        if (archivo.exists()) {
            setImagenLabel(lblParabrisas, archivo.getAbsolutePath());
        }
        frame++;
        if (frame > 3) {
            frame = 1;
        }
    }

    private void actualizarVelocidad(EnumParabrisas velocidad) {
        int delay;
        switch (velocidad) {
            case BAJO -> delay = 1200;
            case MEDIO -> delay = 800;
            case RAPIDO -> delay = 600;
            case APAGADO -> {
            timer.stop();
            ImageIcon icon = new ImageIcon(getClass().getResource("/images/parabrisas1.png"));
            Image scaledImage = icon.getImage().getScaledInstance(lblParabrisas.getWidth(), lblParabrisas.getHeight(), Image.SCALE_SMOOTH);
            lblParabrisas.setIcon(new ImageIcon(scaledImage));
            return;
        }
        default -> delay = 1000;
    }
    timer.setDelay(delay);
    if (!timer.isRunning()) {
        timer.start();
    }
}
    
    private void setImagenLabel(JLabel lblParabrisas, String root) {
        ImageIcon image = new ImageIcon(root);
        int width = lblParabrisas.getWidth();
        int height = lblParabrisas.getHeight();
        if (width > 0 && height > 0) {
             Icon icon = new ImageIcon(image.getImage().getScaledInstance(width, height, Image.SCALE_DEFAULT));
            lblParabrisas.setIcon(icon);
            this.repaint();
        } else {
          lblParabrisas.setIcon(image);
        }
    }

  

