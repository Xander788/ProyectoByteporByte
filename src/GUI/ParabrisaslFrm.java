    private void btnEncenderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEncenderActionPerformed
        if (parabrisas.isActividadParabrisas() == EnumParabrisas.APAGADO) {
            parabrisas.setActividadParabrisas(EnumParabrisas.BAJO);
            actualizarVelocidad(EnumParabrisas.BAJO);
            lblEstado.setText("Estado: Encendido");
            lblVelocidad.setText("Velocidad: " + parabrisas.isActividadParabrisas().getVelocidad());
        } else {
            lblEstado.setText("Parabrisas ya está encendido");
            lblVelocidad.setText("Velocidad: " + parabrisas.isActividadParabrisas().getVelocidad());
        }
    }//GEN-LAST:event_btnEncenderActionPerformed

